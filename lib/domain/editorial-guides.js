export const EDITORIAL_GUIDES = Object.freeze(guides.map((guide) => Object.freeze(guide)));

export function getEditorialGuides() {
  return EDITORIAL_GUIDES;
}

export function getEditorialGuide(slug) {
  const normalized = typeof slug === "string" ? slug.trim() : "";
  return EDITORIAL_GUIDES.find((guide) => guide.slug === normalized) ?? null;
}

export function getEditorialGuideSlugs() {
  return EDITORIAL_GUIDES.map((guide) => guide.slug);
}
