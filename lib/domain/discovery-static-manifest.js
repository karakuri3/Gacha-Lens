export function getStaticDiscoveryFacetParams(type) {
  return staticFacets(type).map(({ name }) => ({ name }));
}

export function getStaticDiscoveryFacetPaginationParams(type, pageSize = 60) {
  const size = Math.max(1, Number(pageSize) || 60);
  return staticFacets(type).flatMap(({ name, series_count }) => {
    const totalPages = Math.max(1, Math.ceil(series_count / size));
    return Array.from({ length: Math.max(0, totalPages - 1) }, (_, index) => ({
      name,
      page: String(index + 2),
    }));
  });
}

function staticFacets(type) {
  if (type === "brand") return STATIC_BRAND_FACETS;
  if (type === "franchise") return STATIC_FRANCHISE_FACETS;
  return [];
}
